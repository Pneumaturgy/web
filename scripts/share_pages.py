#!/usr/bin/env python3
"""Generate a share link for every project sheet in index.html.

For each <article class="sheet-doc" data-doc="KEY"> this writes KEY/index.html:
a tiny page carrying Open Graph tags, so pasting
https://pneumaturgy.github.io/web/KEY/ into Discord, iMessage, Slack, etc.
shows a preview card for that project, and then redirects to /#KEY.

Run it from the repository root after adding or editing a project:

    python3 scripts/share_pages.py

Everything comes from the sheet itself:
  title        the sheet's <h1>
  description  the sheet's lede paragraph
  image        the sheet's first <img>, else the card's <img>, else the flame
  colour       the eyebrow's colour, if it has one

Any of these can be overridden on the <article> with data-share-title,
data-share-description or data-share-image. Standard library only.
"""

import html
import re
import struct
import sys
from pathlib import Path

SITE = "https://pneumaturgy.github.io/web/"
ROOT = Path(__file__).resolve().parent.parent
MARKER = "<!-- generated by scripts/share_pages.py -->"
FALLBACK_IMAGE = "assets/flame.png"


def text(fragment):
    """Strip tags and entities, collapse whitespace."""
    plain = html.unescape(re.sub(r"<[^>]+>", "", fragment))
    return re.sub(r"\s+", " ", plain).strip()


def image_size(path):
    """(width, height) of a PNG or JPEG, or None."""
    data = path.read_bytes()
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", data[16:24])
    if data[:2] == b"\xff\xd8":
        i = 2
        while i < len(data) - 9:
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
                h, w = struct.unpack(">HH", data[i + 5:i + 9])
                return w, h
            i += 2 + struct.unpack(">H", data[i + 2:i + 4])[0]
    return None


def attr(tag, name):
    m = re.search(rf'{name}="([^"]*)"', tag)
    return html.unescape(m.group(1)) if m else None


def page(key, title, description, image, colour):
    size = image_size(ROOT / image)
    wide = size is not None and size[0] >= size[1] * 1.3
    e = lambda v: html.escape(v, quote=True)
    lines = [
        "<!DOCTYPE html>",
        MARKER,
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>{e(title)} · Pneumaturgy</title>",
        f'<meta name="description" content="{e(description)}">',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="Pneumaturgy">',
        f'<meta property="og:title" content="{e(title)}">',
        f'<meta property="og:description" content="{e(description)}">',
        f'<meta property="og:url" content="{SITE}{key}/">',
        f'<meta property="og:image" content="{SITE}{image}">',
    ]
    if size:
        lines += [
            f'<meta property="og:image:width" content="{size[0]}">',
            f'<meta property="og:image:height" content="{size[1]}">',
        ]
    lines += [
        f'<meta name="twitter:card" content="{"summary_large_image" if wide else "summary"}">',
    ]
    if colour:
        lines.append(f'<meta name="theme-color" content="{e(colour)}">')
    lines += [
        f'<meta http-equiv="refresh" content="0; url=../#{key}">',
        f"<script>location.replace('../#{key}');</script>",
        "</head>",
        "<body>",
        f'<p><a href="../#{key}">{e(title)}</a></p>',
        "</body>",
        "</html>",
        "",
    ]
    return "\n".join(lines)


def main():
    source = (ROOT / "index.html").read_text(encoding="utf-8")
    cards = {
        m.group(1): m.group(2)
        for m in re.finditer(r'<button[^>]*data-sheet="([^"]+)"[^>]*>(.*?)</button>', source, re.S)
    }
    articles = list(re.finditer(r'(<article class="sheet-doc"[^>]*>)(.*?)</article>', source, re.S))
    if not articles:
        sys.exit("No project sheets found in index.html")

    for m in articles:
        tag, body = m.groups()
        key = attr(tag, "data-doc")
        h1 = re.search(r"<h1>(.*?)</h1>", body, re.S)
        lede = re.search(r'class="sheet-doc__lede"[^>]*>(.*?)</p>', body, re.S)
        eyebrow = re.search(r'class="sheet-doc__eyebrow"[^>]*style="[^"]*color:\s*(#[0-9A-Fa-f]{3,8})', body)
        images = re.findall(r'<img src="([^"]+)"', body) or re.findall(r'<img src="([^"]+)"', cards.get(key, ""))

        title = attr(tag, "data-share-title") or (text(h1.group(1)) if h1 else key)
        description = attr(tag, "data-share-description") or (text(lede.group(1)) if lede else "")
        image = attr(tag, "data-share-image") or (images[0] if images else FALLBACK_IMAGE)
        colour = eyebrow.group(1) if eyebrow else None

        out = ROOT / key / "index.html"
        ours = out.exists() and MARKER in out.read_text(encoding="utf-8")
        if out.parent.exists() and any(out.parent.iterdir()) and not ours:
            sys.exit(f"{key}/ exists and was not made by this script; rename the sheet or move that folder")
        out.parent.mkdir(exist_ok=True)
        out.write_text(page(key, title, description, image, colour), encoding="utf-8")
        print(f"{SITE}{key}/")


if __name__ == "__main__":
    main()
